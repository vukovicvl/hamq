def reencode_captured(name: str) -> bytes:
    """Build a captured packet again from its decoded values with the hamq encoder."""
    msg = CAPTURED_EXPECTED[name]
    client, schema = msg["client"], msg["schema"]
    if msg["type"] == "heartbeat":
        return encode_heartbeat(client, msg["max_schema"], msg["version"], msg["revision"], schema)
    if msg["type"] == "status":
        optional = {key: msg[key] for key in STATUS_OPTIONAL}
        return encode_status(
            client, msg["freq_hz"], msg["mode"], msg["dx_call"], schema=schema, **optional
        )
    if msg["type"] == "logged_adif":
        return encode_logged_adif(client, msg["adif"], schema, latin1=True)  # as WSJT-X does
    if msg["type"] == "close":
        return encode_close(client, schema)
    return captured_qso_logged_packet()


def status_wire_order(client: str | None) -> list[str]:
    """The optional Status keys in wire order: JTDX (id "JTDX" or "JTDX - <rig>") has its own."""
    if client is not None and client.startswith("JTDX"):
        return JTDX_STATUS_OPTIONAL
    return STATUS_OPTIONAL


def check_message(msg: object) -> None:
    """Shape every decode() result must have (used by the fuzz tests)."""
    if msg is None:
        return
    assert isinstance(msg, dict)
    assert msg["schema"] in (2, 3)
    assert msg["client"] is None or isinstance(msg["client"], str)
    keys = list(msg)
    if msg["type"] == "status":
        assert keys[:6] == STATUS_MANDATORY
        optional = status_wire_order(msg["client"])
        assert keys[6:] == optional[: len(keys) - 6]  # a prefix, in wire order
        assert isinstance(msg["freq_hz"], int)
    else:
        assert keys == KEYS[msg["type"]]


