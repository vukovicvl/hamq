def jtdx_status_packet(client: str = "JTDX", tx_first: bool = True) -> bytes:
    """Status as JTDX's MessageClient::status_update writes it, statement by statement."""
    return (
        Writer()
        .header(STATUS, client, 2)
        .u64(14074000)  # Frequency = quint64
        .utf8("FT8")
        .utf8("DL1ABC")
        .utf8("-10")  # report
        .utf8("FT8")  # Tx mode
        .boolean(True)  # Tx enabled
        .boolean(False)  # transmitting
        .boolean(False)  # decoding
        .i32(1500)  # Rx DF: qint32 in JTDX, quint32 in WSJT-X
        .i32(1210)  # Tx DF
        .utf8("YU1ABC")
        .utf8("KN04ft")
        .utf8("JO62")
        .boolean(False)  # Tx watchdog
        .utf8(None)  # sub-mode: QString {}
        .boolean(False)  # fast mode
        .boolean(tx_first)
        .getvalue()
    )


