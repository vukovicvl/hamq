# --- wire layout of the encoders --------------------------------------------------------------


def test_heartbeat_wire_layout():
    expected = (
        bytes.fromhex("adbccbda 00000002 00000000 00000006")
        + b"WSJT-X"
        + bytes.fromhex("00000003 00000005")
        + b"2.7.0"
        + bytes.fromhex("00000000")  # revision: empty string
    )
    assert encode_heartbeat("WSJT-X") == expected


def test_status_mandatory_wire_layout():
    expected = (
        bytes.fromhex("adbccbda 00000002 00000001 00000006")
        + b"WSJT-X"
        + bytes.fromhex("00000000006bf0d0 00000003")
        + b"FT8"
        + bytes.fromhex("00000006")
        + b"YU7ABC"
    )
    assert encode_status("WSJT-X", 7074000, "FT8", "YU7ABC") == expected


def test_close_and_logged_adif_wire_layout():
    header = bytes.fromhex("adbccbda 00000003 00000006 00000006") + b"WSJT-X"
    assert encode_close("WSJT-X", schema=3) == header
    adif = "<call:6>YU7ABC <EOR>"
    assert encode_logged_adif("WSJT-X", adif) == (
        bytes.fromhex("adbccbda 00000002 0000000c 00000006")
        + b"WSJT-X"
        + len(adif).to_bytes(4, "big")
        + adif.encode()
    )


def test_encode_status_writes_fields_up_to_the_last_one_given():
    msg = decode(encode_status("WSJT-X", 14074000, "FT8", "DL1ABC", decoding=True))
    assert list(msg) == STATUS_MANDATORY + STATUS_OPTIONAL[:5]
    assert msg["report"] == ""
    assert msg["tx_mode"] == ""
    assert msg["tx_enabled"] is False
    assert msg["transmitting"] is False
    assert msg["decoding"] is True

    msg = decode(encode_status("WSJT-X", 14074000, "FT8", tr_period=15))
    assert list(msg) == STATUS_MANDATORY + STATUS_OPTIONAL[:16]
    assert msg["dx_call"] == ""
    assert msg["rx_df"] == msg["tx_df"] == msg["frequency_tolerance"] == 0xFFFFFFFF
    assert msg["special_op_mode"] == 0
    assert msg["tr_period"] == 15


def test_encode_status_rejects_unknown_fields():
    with pytest.raises(TypeError, match="snr"):
        encode_status("WSJT-X", 14074000, "FT8", snr=-10)


def test_encode_status_rejects_values_of_the_wrong_type():
    with pytest.raises(TypeError):
        encode_status("WSJT-X", 14074000, "FT8", tx_enabled="no")
    with pytest.raises(TypeError):
        encode_status("WSJT-X", 14074000, "FT8", rx_df="1500")


def test_encode_status_picks_the_jtdx_layout_by_client_id():
    msg = decode(encode_status("JTDX - IC7300", 14074000, "FT8", "DL1ABC", tx_first=True))
    assert list(msg) == STATUS_MANDATORY + JTDX_STATUS_OPTIONAL
    assert msg["tx_first"] is True
    assert (msg["sub_mode"], msg["fast_mode"]) == ("", False)  # defaults before tx_first
    msg = decode(encode_status("JTDX", 14074000, "FT8", "DL1ABC", de_grid="KN04ft"))
    assert list(msg) == STATUS_MANDATORY + JTDX_STATUS_OPTIONAL[:9]
    # JTDX has no special_op_mode (and nothing after tx_first); WSJT-X has no tx_first
    for field in ("special_op_mode", "frequency_tolerance", "tx_message"):
        with pytest.raises(TypeError, match=field):
            encode_status("JTDX", 14074000, "FT8", **{field: STATUS_FT8[field]})
    for client in ("WSJT-X", "MSHV", None):
        with pytest.raises(TypeError, match="tx_first"):
            encode_status(client, 14074000, "FT8", tx_first=True)


@pytest.mark.parametrize("schema", [0, 1, 4])
def test_encoders_reject_unsupported_schemas(schema):
    with pytest.raises(ValueError):
        encode_heartbeat("WSJT-X", schema=schema)
    with pytest.raises(ValueError):
        encode_status("WSJT-X", 14074000, "FT8", schema=schema)
