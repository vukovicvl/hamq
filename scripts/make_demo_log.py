@dataclass(frozen=True)
class City:
    """A place of stations: name, position, callsign prefixes and zones."""

    name: str
    lat: float
    lon: float
    prefixes: tuple[str, ...]
    cq: int
    itu: int


@dataclass(frozen=True)
class Entity:
    """A DXCC entity of the demo log (name, code and continent as in cty.dat / cty.csv)."""

    country: str
    dxcc: int
    cont: str
    qsos: int  # QSOs with stations of this entity
    hours: tuple[int, int]  # usual UTC hours (start, end; end may be past midnight)
    cities: tuple[City, ...]


def _cities(*rows: tuple[str, float, float, str, int, int]) -> tuple[City, ...]:
    """Cities from rows ``(name, lat, lon, "PFX1 PFX2", cq, itu)``."""
    return tuple(
        City(name, lat, lon, tuple(pfx.split()), cq, itu) for name, lat, lon, pfx, cq, itu in rows
    )


