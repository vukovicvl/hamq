#!/usr/bin/env python3
"""Generate the fictional demo log ``docs/demo/demo_log.adi`` (README screenshots, trying HamQ).

The log has 150 QSOs of the fictional station YU1ZZZ in KN04ft (Beograd), January to
September 2026, with stations on six continents. Every callsign and QSO is made up: the
callsigns are a real prefix of the entity (and of the call area, where it matters) plus
random letters, so they look plausible but may match a real callsign by chance. The
locators are those of real cities of the entity; bands, modes, times and signal reports
follow the usual propagation (6 m sporadic E in early summer, 160 m and 80 m at night, the
Americas in the European afternoon and evening, Japan and Oceania in the morning, ...).

Each record has what a desktop logger exports after its lookups: ``CALL``, ``GRIDSQUARE``,
``MODE`` (FT4 as ``MFSK`` / ``FT4``), ``RST_SENT`` / ``RST_RCVD``, date and time on and off,
``BAND``, ``FREQ``, ``STATION_CALLSIGN``, ``MY_GRIDSQUARE`` and the DXCC data ``COUNTRY``,
``DXCC``, ``CONT``, ``CQZ``, ``ITUZ``. ADIF DXCC codes, continents and zones are those of
the AD1C country files (cty.dat / cty.csv) for each callsign, and the entity names those
HamQ shows, so the log gives the same statistics with or without a downloaded cty.dat
(checked against the release of 15 September 2026).

The output is reproducible: the same seed gives the same file. Usage::

    python3 scripts/make_demo_log.py            # writes docs/demo/demo_log.adi
    python3 scripts/make_demo_log.py --check    # exit status 1 when the file is out of date
"""

