def random_fields(rng: random.Random) -> bytes:
    """A random sequence of well-formed QDataStream fields (lengths mostly plausible)."""
    writer = Writer()
    for _ in range(rng.randrange(0, 24)):
        kind = rng.randrange(6)
        if kind == 0:
            writer.u8(rng.randrange(256))
        elif kind == 1:
            writer.u32(rng.choice([0, 1, 1500, 0xFFFFFFFF, rng.randrange(2**32)]))
        elif kind == 2:
            writer.u64(rng.randrange(2**64))
        elif kind == 3:
            writer.byte_array(rng.randbytes(rng.randrange(12)))
        elif kind == 4:
            writer.utf8(rng.choice(["", "FT8", "YU7ABC", "Đorđe", "KN04ft"]))
        else:
            writer.utf8(None)
    return writer.getvalue()


def test_random_payloads_behind_a_valid_header_never_raise():
    rng = random.Random(2237)
    seen = dict.fromkeys(["heartbeat", "status", "close", "logged_adif", "other"], 0)
    for _ in range(10_000):
        code = rng.choice([HEARTBEAT, STATUS, CLOSE, LOGGED_ADIF, QSO_LOGGED, rng.randrange(2**32)])
        client = rng.choice(["WSJT-X", "JTDX", "", None])
        packet = Writer().header(code, client, rng.choice([2, 3])).getvalue() + random_fields(rng)
        if rng.random() < 0.3:
            packet = packet[: rng.randrange(len(packet) + 1)]
        msg = decode(packet)
        check_message(msg)
        if msg is not None:
            seen[msg["type"]] += 1
    assert min(seen.values()) >= 100, seen  # the fuzzing reaches every message decoder


